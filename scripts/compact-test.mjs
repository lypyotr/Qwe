import assert from 'node:assert/strict';
import fs from 'node:fs';
import {chromium} from 'playwright';
import {testServer,blockExternal} from './test-server.mjs';

const server=await testServer();
const browser=await chromium.launch(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{});
let assertions=0;
const check=(name,value)=>{assert.ok(value,name);assertions++;console.log('PASS:',name);};
fs.mkdirSync('artifacts/design',{recursive:true});
let png;
try{
  const context=await browser.newContext({serviceWorkers:'block',reducedMotion:'reduce',viewport:{width:390,height:844}});
  await blockExternal(context);
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const ready=async()=>{await page.goto(server.url,{waitUntil:'networkidle'});await page.evaluate(()=>{showAuthOverlay(false);hideLoader();});};
  await ready();
  png=Buffer.from(await page.evaluate(()=>{const c=document.createElement('canvas');c.width=8;c.height=8;const ctx=c.getContext('2d');ctx.fillStyle='#77aa66';ctx.fillRect(0,0,8,8);return c.toDataURL('image/png').split(',')[1];}),'base64');
  check('new installation starts in the approved light palette',await page.evaluate(()=>document.body.classList.contains('light')));
  await page.evaluate(()=>{
    currentUser={id:'avatar-test-user'};sbClient=null;
    goals={period:60000,week:10000,month:120000,profile:{name:'Рудольф'}};
    goToHistory('2026-9',2);selectDay(23);
    days={23:[{id:1,name:'Сборка и монтаж каркаса',qty:12,price:350},{id:2,name:'Подготовка деталей',qty:8,price:175}]};
    bonuses=[];expenseItems=[];templates=[{id:77,name:'Раскрой',price:250}];renderAll();switchPage('work');
  });
  check('filled work is a compact summary with its own amount',await page.locator('#dayWorks .work-summary').count()===2&&await page.locator('#dayWorks .work-editor:visible').count()===0&&await page.locator('#dayWorks .work-summary-sum').first().textContent()==='4 200 ₽');
  const first=page.locator('#dayWorks [data-work-id="1"]');
  await first.locator('.work-summary').click();
  await first.locator('.dw-qty-wrap input').fill('15');
  check('editing updates the line and day totals without losing focus',await page.evaluate(()=>daySum(23)===6650&&document.activeElement.closest('.dw-qty-wrap'))&&await first.locator('.work-summary-sum').textContent()==='5 250 ₽');
  await first.locator('.work-done').click();
  check('done collapses the editor and restores its summary focus',await first.locator('.work-editor').isHidden()&&await page.evaluate(()=>document.activeElement.classList.contains('work-summary')));
  await page.locator('.tpl-use').click();
  await page.waitForFunction(()=>document.activeElement?.closest('.dw-qty-wrap'));
  check('a template opens its quantity for immediate entry',await page.evaluate(()=>days[23].length===3&&days[23][2].price==='250'&&document.activeElement.closest('.is-editing')));
  await page.evaluate(()=>{days[23].pop();editingWorkId=null;days[23][0].qty=12;renderAll();});
  for(const width of [320,390,768,999,1000,1440]){
    await page.setViewportSize({width,height:960});
    check('compact journal has no horizontal overflow at '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#workspaceAvatar').click();
  const box=await page.locator('#workspaceAvatarDialog').boundingBox();
  check('avatar opens centered on desktop',Math.abs(box.x+box.width/2-720)<2&&Math.abs(box.y+box.height/2-500)<2);
  for(let i=0;i<9;i++)await page.keyboard.press('Tab');
  check('native dialog keeps keyboard focus inside',await page.evaluate(()=>document.activeElement.closest('#workspaceAvatarDialog')));
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  check('Escape returns focus to the avatar',await page.evaluate(()=>document.activeElement.id==='workspaceAvatar'));
  await page.locator('#workspaceAvatar').click();
  await page.locator('#avatarFile').setInputFiles({name:'invalid.txt',mimeType:'text/plain',buffer:Buffer.from('not an image')});
  check('invalid files produce a recoverable error',await page.locator('#avatarError').textContent()!==''&&await page.locator('#avatarSave').isEnabled());
  const choosePhoto=async()=>{
    await page.locator('#avatarFile').setInputFiles({name:'avatar.png',mimeType:'image/png',buffer:png});
    await page.waitForFunction(()=>!!document.querySelector('#avatarPreview img')&&!document.getElementById('avatarSave').disabled);
  };
  await choosePhoto();
  check('photo selection is only a preview until save',await page.evaluate(()=>!goals.profile.avatar));
  await page.locator('#avatarClose').click();
  await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  check('closing discards an unsaved photo',await page.evaluate(()=>!goals.profile.avatar&&!document.querySelector('#workspaceAvatar img')));
  await page.locator('#workspaceAvatar').click();await choosePhoto();await page.locator('#avatarSave').click();
  await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  check('save preserves profile fields and plan targets',await page.evaluate(()=>goals.period===60000&&goals.profile.name==='Рудольф'&&goals.profile.avatar.startsWith('data:image/jpeg;base64,')&&document.querySelector('#workspaceAvatar img')?.src===goals.profile.avatar));
  await ready();
  await page.evaluate(()=>{currentUser={id:'avatar-test-user'};sbClient=null;switchPage('work');});
  check('saved photo survives reload',await page.locator('#workspaceAvatar img').count()===1);
  await page.locator('#workspaceAvatar').click();await page.locator('#avatarRemove').click();await page.locator('#avatarClose').click();
  await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  check('canceling removal keeps the saved photo',await page.locator('#workspaceAvatar img').count()===1);
  await page.locator('#workspaceAvatar').click();await page.locator('#avatarRemove').click();await page.locator('#avatarSave').click();
  await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  check('saving removal restores the initial',await page.evaluate(()=>goals.profile.avatar===''&&!document.querySelector('#workspaceAvatar img')&&document.getElementById('workspaceAvatar').textContent==='Р'));
  await page.locator('#workspaceAvatar').click();
  await page.evaluate(()=>{currentUser={id:'a-different-account'};goals={profile:{name:'Другой'}};workspaceRenderAvatar();});
  check('account switch clears an opened avatar editor',await page.evaluate(()=>!document.getElementById('workspaceAvatarDialog').open&&document.getElementById('workspaceAvatar').textContent==='Д'));
  await page.setViewportSize({width:390,height:844});
  await page.locator('#workspaceAvatar').click();
  const mobileBox=await page.locator('#workspaceAvatarDialog').boundingBox();
  check('avatar dialog fits and remains centered on mobile',mobileBox.x>=0&&mobileBox.x+mobileBox.width<=390&&Math.abs(mobileBox.y+mobileBox.height/2-422)<2);
  await page.screenshot({path:'artifacts/design/avatar-light-390.png'});
  await page.locator('#avatarClose').click();await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  await page.evaluate(()=>switchPage('profile'));await page.locator('#profileAvatar').click();
  check('profile avatar opens the same settings dialog',await page.locator('#workspaceAvatarDialog').isVisible());
  await page.locator('#avatarClose').click();await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.locator('#profileAvatar').click();
  check('open animation combines 160ms fade and scale',await page.evaluate(()=>document.getElementById('workspaceAvatarDialog').getAnimations().some(a=>a.effect.getTiming().duration===160&&a.effect.getKeyframes().some(f=>f.transform==='scale(0.96)'))));
  await page.waitForTimeout(180);await page.locator('#avatarClose').click();await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  await page.emulateMedia({reducedMotion:'reduce'});await page.locator('#profileAvatar').click();
  check('reduced motion skips the avatar animation',await page.evaluate(()=>document.getElementById('workspaceAvatarDialog').getAnimations().length===0));
  await page.locator('#avatarClose').click();await page.waitForFunction(()=>!document.getElementById('workspaceAvatarDialog').open);
  await page.evaluate(()=>{switchPage('work');document.body.classList.remove('light');});await page.locator('#workspaceAvatar').click();
  await page.screenshot({path:'artifacts/design/avatar-dark-390.png'});
  check('no uncaught UI errors',errors.length===0);
  console.log('compact and avatar tests OK: '+assertions+' assertions');
}finally{await browser.close();await server.close();}
